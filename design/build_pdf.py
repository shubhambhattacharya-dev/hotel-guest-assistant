MAX_KEEP = AVAIL_H * 0.45   # cap on keep-together blocks (heading + atomic content)

def keep_block(elements, max_h=None):
    """KeepTogether unless the block is too tall; then keep only the first two."""
    max_h = max_h or MAX_KEEP
    total = 0
    for el in elements:
        try:
            _, h = el.wrap(AVAIL, AVAIL_H)
        except Exception:
            h = 0
        total += h
    if total <= max_h:
        return [KeepTogether(list(elements))]
    if len(elements) >= 2:
        return [KeepTogether(list(elements[:2]))] + list(elements[2:])
    return list(elements)

