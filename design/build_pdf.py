DARK = TEXT_PRIMARY

def _rrect(d, x, y, w, h, fill, stroke, sw=0.9, dash=None):
    r = Rect(x, y, w, h, rx=4, ry=4)
    r.fillColor = fill
    r.strokeColor = stroke
    r.strokeWidth = sw
    if dash:
        r.strokeDashArray = dash
    d.add(r)

def _text(d, x, y, s, size=10, color=DARK, bold=False, anchor='middle'):
    st = String(x, y, s)
    st.fontName = 'Times New Roman Bold' if bold else 'Times New Roman'
    st.fontSize = size
    st.fillColor = color
    st.textAnchor = anchor
    d.add(st)

def _arrow_down(d, x, y_top, y_bot, color=HEADER_FILL):
    d.add(Line(x, y_top, x, y_bot + 3.5, strokeColor=color, strokeWidth=1.0))
    d.add(Polygon(points=[x - 3, y_bot + 3.5, x + 3, y_bot + 3.5, x, y_bot],
                  fillColor=color, strokeColor=color))

def vflow(nodes, width=None, box_w=300):
    """Vertical flow. nodes: list of (title, sub|None, kind) with kind in step|key."""
    width = width or AVAIL * 0.9
    gap = 13
    hs = [33 if sub else 24 for (_, sub, _) in nodes]
    total = sum(hs) + gap * (len(nodes) - 1)
    d = Drawing(width, total)
    cx = width / 2.0
    y = total
    for i, (title, sub, kind) in enumerate(nodes):
        h = hs[i]
        bx, by = cx - box_w / 2.0, y - h
        fill = colors.white if kind == 'key' else CARD_BG
        border = ACCENT if kind == 'key' else HEADER_FILL
        _rrect(d, bx, by, box_w, h, fill, border, 1.2 if kind == 'key' else 0.9)
        if sub:
            _text(d, cx, by + h - 16, title, 10, TEXT_PRIMARY, bold=True)
            _text(d, cx, by + 6.5, sub, 8, TEXT_MUTED)
        else:
            _text(d, cx, by + h / 2 - 3.5, title, 10, TEXT_PRIMARY, bold=(kind == 'key'))
        if i < len(nodes) - 1:
            _arrow_down(d, cx, by - 1.5, by - gap + 2)
        y = by - gap
    return d

